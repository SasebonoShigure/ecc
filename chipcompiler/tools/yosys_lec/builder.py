#!/usr/bin/env python
import os
import stat

from chipcompiler.data import Workspace, WorkspaceStep


def _derive_golden_path(gate_verilog: str) -> str:
    if not gate_verilog:
        return ""

    directory = os.path.dirname(gate_verilog)
    stem, ext = os.path.splitext(os.path.basename(gate_verilog))
    return os.path.join(directory, f"{stem}_golden{ext or '.v'}")


def _tcl_quote(value: str) -> str:
    value = str(value)
    # Use braces to prevent Tcl variable/command substitution.
    escaped = value.replace("\\", "\\\\").replace("{", "\\{").replace("}", "\\}")
    return "{" + escaped + "}"


def _tcl_list(values: list[str]) -> str:
    return " ".join(_tcl_quote(value) for value in values if value)


def _bool_tcl(value: bool) -> str:
    return "true" if value else "false"


def build_step(
    workspace: Workspace,
    step_name: str,
    input_def: str,
    input_verilog: str,
    input_db: str | None = None,
    output_def: str | None = None,
    output_verilog: str | None = None,
    output_gds: str | None = None,
) -> WorkspaceStep:
    step = WorkspaceStep()
    step.name = step_name
    step.tool = "yosys_lec"
    step.version = "0.1"
    step.directory = f"{workspace.directory}/{step.name}_{step.tool}"

    step.input = {
        "gate_verilog": input_verilog,
        "golden_verilog": input_db or _derive_golden_path(input_verilog),
        "db": input_db,
    }

    step.output = {
        "dir": f"{step.directory}/output",
        "json": f"{step.directory}/output/{workspace.design.name}_{step.name}_result.json",
    }

    step.data = {
        "dir": f"{step.directory}/data",
        "config": f"{step.directory}/data/lec_config.tcl",
    }

    step.report = {
        "dir": f"{step.directory}/report",
        "status": f"{step.directory}/report/run_lec_status.rpt",
        "equiv_status": f"{step.directory}/report/equiv_status.rpt",
        "failed_rtlil": f"{step.directory}/report/equiv_failed.il",
        "failed_verilog": f"{step.directory}/report/equiv_failed.v",
    }

    step.log = {
        "dir": f"{step.directory}/log",
        "file": f"{step.directory}/log/{step.name}.log",
    }

    step.script = {
        "dir": f"{step.directory}/script",
        "main": f"{step.directory}/script/run_lec.tcl",
    }

    step.analysis = {
        "dir": f"{step.directory}/analysis",
        "metrics": f"{step.directory}/analysis/{step.name}_metrics.json",
    }

    step.subflow = {
        "path": f"{step.directory}/subflow.json",
        "steps": [],
    }

    step.checklist = {
        "path": f"{step.directory}/checklist.json",
        "checklist": [],
    }

    return step


def build_step_space(step: WorkspaceStep) -> None:
    os.makedirs(step.directory, exist_ok=True)
    os.makedirs(step.output.get("dir", f"{step.directory}/output"), exist_ok=True)
    os.makedirs(step.data.get("dir", f"{step.directory}/data"), exist_ok=True)
    os.makedirs(step.report.get("dir", f"{step.directory}/report"), exist_ok=True)
    os.makedirs(step.log.get("dir", f"{step.directory}/log"), exist_ok=True)
    os.makedirs(step.script.get("dir", f"{step.directory}/script"), exist_ok=True)
    os.makedirs(step.analysis.get("dir", f"{step.directory}/analysis"), exist_ok=True)


def _write_file(path: str, content: str) -> None:
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
    try:
        os.chmod(path, os.stat(path).st_mode | stat.S_IWUSR)
    except OSError:
        pass


def _lec_parameters(workspace: Workspace) -> dict:
    data = getattr(getattr(workspace, "parameters", None), "data", {}) or {}
    return data.get("LEC", {}) if isinstance(data.get("LEC", {}), dict) else {}


def build_step_config(workspace: Workspace, step: WorkspaceStep) -> None:
    params = _lec_parameters(workspace)
    model_files = params.get("model_files", [])
    if isinstance(model_files, str):
        model_files = [model_files]

    blacklist = str(params.get("blacklist", "") or "")
    use_undef = bool(params.get("use_undef", False))
    liberty_files = getattr(workspace.pdk, "libs", []) or []

    config = f"""# Auto-generated by yosys_lec.builder - DO NOT EDIT MANUALLY
set top_design {_tcl_quote(workspace.design.top_module)}
set golden_file {_tcl_quote(step.input.get("golden_verilog", ""))}
set gate_file {_tcl_quote(step.input.get("gate_verilog", ""))}
set report_dir {_tcl_quote(step.report.get("dir", ""))}
set result_json {_tcl_quote(step.output.get("json", ""))}
set status_file {_tcl_quote(step.report.get("status", ""))}
set equiv_status_file {_tcl_quote(step.report.get("equiv_status", ""))}
set failed_rtlil_file {_tcl_quote(step.report.get("failed_rtlil", ""))}
set failed_verilog_file {_tcl_quote(step.report.get("failed_verilog", ""))}
set liberty_files [list {_tcl_list(liberty_files)}]
set model_files [list {_tcl_list(model_files)}]
set blacklist_file {_tcl_quote(blacklist)}
set use_undef {_bool_tcl(use_undef)}
"""
    _write_file(step.data["config"], config)

    script = """proc require_file {label path} {
    if {$path eq ""} {
        error "$label is empty"
    }
    if {![file exists $path]} {
        error "missing $label: $path"
    }
    if {![file readable $path]} {
        error "$label is not readable: $path"
    }
}

proc read_support_models {} {
    global liberty_files model_files
    foreach liberty_file $liberty_files {
        require_file "liberty file" $liberty_file
        yosys read_liberty -ignore_miss_func -ignore_miss_data_latch $liberty_file
    }
    foreach model_file $model_files {
        require_file "LEC model file" $model_file
        yosys read_verilog -sv $model_file
    }
}

proc normalize_design {top_design} {
    yosys hierarchy -top $top_design
    yosys proc
    yosys memory
    yosys async2sync
    yosys flatten
    yosys splitnets -ports -format __v
    yosys opt_clean -purge
}

proc build_design {stash_name top_design netlist_file} {
    read_support_models
    yosys read_verilog -sv $netlist_file
    normalize_design $top_design
    yosys design -stash $stash_name
}

proc write_failure_artifacts {reason} {
    global status_file equiv_status_file failed_rtlil_file failed_verilog_file
    set handle [open $status_file "w"]
    puts $handle "Yosys LEC did not prove equivalence."
    puts $handle ""
    puts $handle "Reason:"
    puts $handle $reason
    close $handle

    catch {yosys tee -o $equiv_status_file equiv_status}
    catch {yosys write_rtlil $failed_rtlil_file}
    catch {yosys write_verilog -noattr $failed_verilog_file}
}

proc run_equivalence {} {
    global top_design blacklist_file use_undef equiv_status_file
    yosys design -copy-from gold -as gold $top_design
    yosys design -copy-from gate -as gate $top_design
    if {$blacklist_file ne ""} {
        require_file "LEC blacklist" $blacklist_file
        yosys equiv_make -blacklist $blacklist_file gold gate equiv
    } else {
        yosys equiv_make gold gate equiv
    }
    yosys hierarchy -top equiv
    yosys opt_clean -purge

    if {$use_undef} {
        yosys equiv_simple -undef
        yosys equiv_induct -undef
    } else {
        yosys equiv_simple
        yosys equiv_induct
    }
    yosys tee -o $equiv_status_file equiv_status

    set handle [open $equiv_status_file "r"]
    set status_text [read $handle]
    close $handle
    if {![regexp {Equivalence successfully proven!} $status_text]
        && ![regexp {Found a total of 0 unproven \$equiv cells\.} $status_text]} {
        error "equivalence proof has unproven cells; see $equiv_status_file"
    }
}

set script_dir [file dirname [file normalize [info script]]]
source [file normalize [file join $script_dir .. data lec_config.tcl]]
file mkdir $report_dir

require_file "golden netlist" $golden_file
require_file "gate netlist" $gate_file

set result [catch {
    build_design gold $top_design $golden_file
    yosys design -reset
    build_design gate $top_design $gate_file
    yosys design -reset
    run_equivalence
} message]

if {$result != 0} {
    write_failure_artifacts $message
    exit 1
}

set handle [open $status_file "w"]
puts $handle "Yosys LEC completed with proven equivalence."
puts $handle "Golden: $golden_file"
puts $handle "Gate: $gate_file"
close $handle
"""
    _write_file(step.script["main"], script)

    from chipcompiler.tools.yosys_lec.subflow import YosysLecSubFlow

    subflow = YosysLecSubFlow(workspace=workspace, workspace_step=step)
    subflow.build_sub_flow()
